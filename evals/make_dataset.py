"""Writes evals/dataset.json. Ids are plain Gutenberg numbers here and checked against the
catalogue snapshot, so a typo fails loudly instead of silently lowering a score."""

import json
import sys

ROOT = str(__import__("pathlib").Path(__file__).resolve().parent.parent)
CATALOGUE = json.load(open(f"{ROOT}/evals/catalogue.json"))
IDS = {int(k.split(":")[1]) for k in CATALOGUE}

CASES = []


def case(
    id,
    category,
    user,
    *,
    ideal=(),
    relevant=(),
    relevant_where=None,
    forbidden=(),
    forbidden_where=None,
    expect="books",
    history=(),
    note=None,
):
    for n in (*ideal, *relevant, *forbidden):
        if n not in IDS:
            sys.exit(f"{id}: unknown book id {n}")
    messages = []
    for role, content in history:
        if role == "assistant":  # a list of recommended ids -> markdown like the agent writes
            content = "\n".join(
                f"{i}. **[{CATALOGUE[f'gutenberg:{n}']['title']}]"
                f"(https://www.gutenberg.org/ebooks/{n})**"
                for i, n in enumerate(content, start=1)
            )
        messages.append({"role": role, "content": content})
    messages.append({"role": "user", "content": user})
    entry = {"id": id, "category": category, "messages": messages, "expect": expect}
    if ideal:
        entry["ideal"] = [f"gutenberg:{n}" for n in ideal]
    if relevant:
        entry["relevant"] = [f"gutenberg:{n}" for n in relevant]
    if relevant_where:
        entry["relevant_where"] = relevant_where
    if forbidden:
        entry["forbidden"] = [f"gutenberg:{n}" for n in forbidden]
    if forbidden_where:
        entry["forbidden_where"] = forbidden_where
    if note:
        entry["note"] = note
    CASES.append(entry)


